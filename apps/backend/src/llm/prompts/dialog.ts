/** Однокальный режим (§5.4, опция): тьютор+судья одним вызовом (эталон в контексте). */
export function singleCallSystemPrompt(params: {
  language: Language;
  difficulty: Difficulty;
  scenario: string;
  sections?: string[];
  referenceSolution: string;
  rubricKeyPoints: string[];
  answerReachedCriteria: string;
}): string {
  return [
    tutorSystemPrompt(params),
    '',
    'Одновременно ты — судья. Эталон и тезисы ниже СТРОГО не раскрывай студенту.',
    judgeSystemPrompt(params),
    '',
    'В этом режиме после student_reached_answer добавь в тот же JSON поле "tutor_message" — реплику тьютора по правилам выше (без ответа).',
  ].join('\n');
}

/* ── Семантическая проверка утечки (A21) ────────────────────────── */

const LEAK_EXCERPT_CHARS = 1500;

/**
 * Проверка реплики тьютора. Статичная часть (тезисы + фрагмент эталона) — первой,
 * как кешируемый префикс; реплики студента и тьютора — в сообщении пользователя.
 */
export function leakCheckSystemPrompt(params: { rubricKeyPoints: string[]; referenceSolution: string }): string {
  return [
    'Ты — контролёр учебного диалога. Проверь реплику ТЬЮТОРА: не раскрывает ли она студенту ответ.',
    'ТЕЗИСЫ ОТВЕТА:',
    ...params.rubricKeyPoints.map((p, i) => `K${i + 1}. ${p}`),
    `ЭТАЛОН (фрагмент): ${params.referenceSolution.slice(0, LEAK_EXCERPT_CHARS)}`,
    '',
    'ВОПРОС: формулирует, перечисляет или выдаёт в виде плана реплика тьютора какой-либо тезис или вывод, который студент ещё НЕ установил сам в своих репликах, либо даёт критерии оценивания или структуру ответа?',
    'Раскрытием считается и наводящий вопрос с уже вложенным готовым ответом: он называет тип, теорию, механизм или вывод, которых студент ещё не называл сам; а также прямое подтверждение или опровержение правильности утверждения студента («верно», «да, это так», «нет, это не так»).',
    'НЕ считается раскрытием: вопрос о признаках или основаниях без готового ответа; указание раздела или темы курса; нейтральный пересказ того, что уже сказал сам студент; общий призыв обосновать мысль.',
    'Верни СТРОГО JSON: {"leaks": true|false, "reason": "не более 12 слов"}',
  ].join('\n');
}

export function leakCheckUserMessage(params: { studentTurns: string[]; reply: string }): string {
  return [
    'РЕПЛИКИ СТУДЕНТА (уже установлено им самим):',
    params.studentTurns.length ? params.studentTurns.map((t) => `- ${t}`).join('\n') : '(нет)',
    '',
    `РЕПЛИКА ТЬЮТОРА ДЛЯ ПРОВЕРКИ: ${params.reply}`,
  ].join('\n');
}

