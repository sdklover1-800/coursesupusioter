export function evaluationSummaryUserMessage(turns: { id: string; content: string; scores: Record<string, number> | null }[]): string {
  return [
    'РЕПЛИКИ СТУДЕНТА:',
    ...turns.map((t) => {
      const s = t.scores
        ? ` (баллы: ${Object.entries(t.scores)
            .map(([k, v]) => `${k}=${v}`)
            .join(', ')})`
        : '';
      return `[id=${t.id}]${s} ${t.content}`;
    }),
  ].join('\n');
}

function toRoman(n: number): string {
  const map: [number, string][] = [
    [10, 'X'],
    [9, 'IX'],
    [5, 'V'],
    [4, 'IV'],
    [1, 'I'],
  ];
  let out = '';
  for (const [v, s] of map) while (n >= v) {
    out += s;
    n -= v;
  }
  return out;
}
