/* ── Судья (§5.4, §5.5, калибровка A.1, A2, A4) ─────────────────── */

/** Реплика транскрипта для судьи/проверки: роль и текст. */
export interface TranscriptLine {
  role: 'AI' | 'STUDENT';
  content: string;
}

/**
 * Транскрипт одним сообщением с явными метками ролей: судья должен видеть, какие
 * слова принадлежат студенту, а какие — тьютору (слова тьютора не засчитываются).
 * Префикс транскрипта стабилен от хода к ходу — провайдер кеширует его (A3).
 */
export function judgeTranscript(lines: readonly TranscriptLine[]): string {
  let t = 0;
  let s = 0;
  const out = lines.map((l) => (l.role === 'AI' ? `[Т${++t}] ТЬЮТОР: ${l.content}` : `[С${++s}] СТУДЕНТ: ${l.content}`));
  const lastStudent = s > 0 ? `[С${s}]` : 'нет';
  return [
    'ТРАНСКРИПТ ДИАЛОГА:',
    ...out,
    '',
    `Последняя реплика студента: ${lastStudent}. Оцени по правилам и верни JSON.`,
  ].join('\n');
}

