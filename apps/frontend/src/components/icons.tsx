export type IconName = keyof typeof PATHS;
export const ICON_NAMES = Object.keys(PATHS) as IconName[];

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, 'name'> {
  name: IconName;
  /** 16 | 20 | 24 (любое число допустимо) */
  size?: number;
  /** Доступное имя: без него иконка декоративная */
  label?: string;
  strokeWidth?: number;
}

export function Icon({ name, size = 20, label, strokeWidth = 1.5, className, ...rest }: IconProps) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      className={className ? `shrink-0 ${className}` : 'shrink-0'}
      role={label ? 'img' : undefined}
      aria-label={label}
      aria-hidden={label ? undefined : true}
      focusable="false"
      {...rest}
    >
      {PATHS[name]}
    </svg>
  );
}

type NamedIconProps = Omit<IconProps, 'name'>;
const make = (name: IconName) => {
  const C = (p: NamedIconProps) => <Icon name={name} {...p} />;
  C.displayName = `Icon(${name})`;
  return C;
};

